const { withAndroidManifest, withDangerousMod, AndroidConfig } = require('expo/config-plugins');
const fs = require('fs');
const path = require('path');

/**
 * Restricts Android Auto Backup to the database and the Day 0 photo set.
 *
 * Auto Backup is on by default (Expo sets `allowBackup` true) and silently copies app data to
 * the user's own Google Drive, restoring it on reinstall. The trap is its **25MB per-app cap**:
 * past that, Android stops backing the app up *entirely* rather than partially — so once a user
 * accumulates a few months of progress photos, they lose backup coverage for the database too,
 * with no warning, exactly when their history has become worth keeping.
 *
 * Listing explicit `<include>` rules makes backup opt-in: only these paths are copied, so the
 * total stays small permanently. What survives a reinstall is the routine and every logged dose
 * (tiny, and impossible to reconstruct from memory) plus the baseline photos every future
 * comparison is measured against. Later photo sets are not backed up — that needs a real
 * export/restore feature, which this is not a substitute for.
 *
 * Paths, both under `filesDir` and so `domain="file"`:
 *   SQLite/                        expo-sqlite's directory (SQLiteModule.kt: filesDir + "/SQLite")
 *   progress-photos/baseline/      see BASELINE_DIRNAME in features/photos/api.ts
 *
 * Prebuild warns that "expo-secure-store tried to apply Android Auto Backup rules, but other
 * backup rules are already present". That's expected and safe here. SecureStore wants its own
 * data *excluded* from backup, because values encrypted with a device-bound key can't be
 * decrypted after restoring onto a different phone. These rules are include-only, so anything
 * not listed — SecureStore's shared preferences included — is already excluded. Don't "fix" the
 * warning by adding SecureStore paths back in.
 *
 * Two files because Android switched formats: `fullBackupContent` is used up to Android 11,
 * `dataExtractionRules` from Android 12. Both must exist and agree, or devices on one side of
 * that line silently fall back to backing up everything.
 */

const FULL_BACKUP_CONTENT = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/with-backup-rules.js — edit that, not this. -->
<full-backup-content>
    <include domain="file" path="SQLite/" />
    <include domain="file" path="progress-photos/baseline/" />
</full-backup-content>
`;

const DATA_EXTRACTION_RULES = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/with-backup-rules.js — edit that, not this. -->
<data-extraction-rules>
    <cloud-backup>
        <include domain="file" path="SQLite/" />
        <include domain="file" path="progress-photos/baseline/" />
    </cloud-backup>
    <device-transfer>
        <include domain="file" path="SQLite/" />
        <include domain="file" path="progress-photos/baseline/" />
    </device-transfer>
</data-extraction-rules>
`;

function writeXmlFiles(config) {
  return withDangerousMod(config, [
    'android',
    async (cfg) => {
      const xmlDir = path.join(cfg.modRequest.platformProjectRoot, 'app/src/main/res/xml');
      fs.mkdirSync(xmlDir, { recursive: true });
      fs.writeFileSync(path.join(xmlDir, 'backup_rules.xml'), FULL_BACKUP_CONTENT);
      fs.writeFileSync(path.join(xmlDir, 'data_extraction_rules.xml'), DATA_EXTRACTION_RULES);
      return cfg;
    },
  ]);
}

function pointManifestAtRules(config) {
  return withAndroidManifest(config, (cfg) => {
    const app = AndroidConfig.Manifest.getMainApplicationOrThrow(cfg.modResults);
    app.$['android:fullBackupContent'] = '@xml/backup_rules';
    app.$['android:dataExtractionRules'] = '@xml/data_extraction_rules';
    return cfg;
  });
}

module.exports = function withBackupRules(config) {
  return pointManifestAtRules(writeXmlFiles(config));
};
